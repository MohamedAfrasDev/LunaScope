"""Write the review record of a reference run from its SAVED bundles and manifest.

  python scripts/reference_report.py <dir-with-bundles-and-manifest> [--out docs/runs/GR-001-run.md]

Every number comes from the bundles; nothing is typed in. Gate 2's five checks and the validation card
groups are recomputed here from the same bundles, so the record cannot disagree with them.
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

from lunascope.cards import run_cards
from lunascope.dem import REPO
from lunascope.reference import gate_report

LABEL = {"sun_center": "Sun", "earth_center": "Earth"}


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}%"


def rng(m: dict) -> str:
    lo, hi = pct(m["availability_lower"], 2), pct(m["availability_upper"], 2)
    return lo if lo == hi else f"{lo} to {hi}"


def hms(s: float) -> str:
    s = round(s)
    return f"{s // 86400} d {s % 86400 // 3600:02d} h {s % 3600 // 60:02d} min"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("directory")
    ap.add_argument("--out", default=str(REPO / "docs" / "runs" / "GR-001-run.md"))
    a = ap.parse_args()
    d = Path(a.directory)
    manifest = json.loads((d / "manifest.json").read_text(encoding="utf-8"))
    bundles = [json.loads(Path(f).read_text(encoding="utf-8")) for f in sorted(glob.glob(str(d / "*_*.json")))]
    bundles.sort(key=lambda b: b["request"]["site"]["lon_east_deg"])  # a stable, readable order
    store = REPO / "var" / "horizons"
    gates = gate_report(bundles, horizon_dir=store if store.is_dir() else None)
    cards = run_cards({"run_id": manifest["run_id"], "result_state": bundles[0]["result_state"], "sites": bundles, "validated_scopes": []})
    req = bundles[0]["request"]
    eff = bundles[0]["effective_settings"]
    frozen = manifest.get("frozen")

    L = [f"# {manifest['reference_id']}: run record", "",
         f"**State: `{bundles[0]['result_state']}`** · definition {'**frozen**' if frozen else 'draft (not frozen)'} · "
         f"{'Gate 2 checks pass' if gates['passes'] else 'Gate 2 checks do not pass'}. A passing run is internally consistent, converged and checked "
         "against SPICE. It is **not** a validation of the science: the DEM is not scientifically approved and SDR-001 is unsigned.", "",
         "Generated by `science/scripts/reference_report.py` from the saved bundles. Reproduce the run with "
         "`science/scripts/reference_run.py run GR-001` (live Horizons responses are cached verbatim, so a re-run needs no new requests).", "",
         "## What ran", "", "| Item | Value |", "| --- | --- |",
         f"| Reference run id | `{manifest['run_id'][:16]}...` |",
         f"| Window | {req['mission']['start_utc']}, {req['mission']['duration_s'] // 86400} days, {req['mission']['step_s'] // 60} minute step |",
         f"| Requirements (scenario values) | Sun at least {pct(req['requirements']['sun_center'], 0)}, Earth at least {pct(req['requirements']['earth_center'], 0)} |",
         f"| Terrain | `{eff.get('dem_profile', 'lola-80s-20m-adj')}`, radius {eff['radius_km']:g} km, azimuth step {eff['az_step_deg']:g} deg, mast {eff['observer_height_m']:g} m |",
         "| Resources | " + ", ".join(f"{r['role']} `{r['sha256'][:12]}...`" for r in bundles[0]["resources"]) + " |",
         f"| Code | commit `{manifest['commit'][:12]}`{' with **uncommitted changes**, so this run is not yet reproducible from a commit' if manifest['dirty'] else ''}, algorithm {manifest['algorithm_version']} |",
         f"| Definition SHA-256 | `{manifest['definition_sha256'][:16]}...` |",
         "| Sites | " + "; ".join(f"`{b['request']['site']['site_id']}` ({b['request']['site']['lat_deg']} deg, {b['request']['site']['lon_east_deg']:g} E)" for b in bundles)
         + ". **Rule-chosen points, not candidate landing sites** (SDR-001 D-09). |", "",
         "## Gate 2: the five checks", "", "| Check | Result | What was checked |", "| --- | --- | --- |"]
    for g in gates["gates"]:
        L.append(f"| {g['gate'].replace('_', ' ')} | **{g['status'].replace('_', ' ')}** | {g['detail']} |")
    L += ["", "## Results (terrain-aware decides; the flat horizon is the comparison)", "",
          "| Site | Target | Terrain outcome | Terrain availability | Flat outcome | Flat availability | Longest known hidden | Events | Best clearance over the skyline |",
          "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for b in bundles:
        for t in ("sun_center", "earth_center"):
            r, f = b["targets"][t]["terrain"], b["targets"][t]["flat"]
            c = r.get("clearance_at_nodes")
            L.append(f"| `{b['request']['site']['site_id']}` | {LABEL[t]} | **{r['metrics']['outcome']}** | {rng(r['metrics'])} | {f['metrics']['outcome']} | "
                     f"{rng(f['metrics'])} | {hms(r['metrics']['longest_known_hidden_s'])} | {len(r['events'])} | "
                     f"{'unknown' if not c else f'{c['max_deg']:+.2f} deg'} |")
    L += ["", "## Geometry checks", "", "| Site | Target | SPICE max disagreement | Tolerance | Interpolation holdout | Allowance used |", "| --- | --- | --- | --- | --- | --- |"]
    for b in bundles:
        for t in ("sun_center", "earth_center"):
            g = b["geometry"][t]
            ra = g["reference_agreement"]
            L.append(f"| `{b['request']['site']['site_id']}` | {LABEL[t]} | {ra['max_total_arcsec']:.4f} arcsec | {ra['tolerance_arcsec']} arcsec | {g['holdout']['max_deg']:.1e} deg | {g['delta_geom_used_deg']:.0e} deg |")
    L += ["", "## Convergence (one setting changed at a time against the base)", "",
          "Base: 10 minute step, 0.1 deg azimuth step, 150 km radius. A case is flagged SENSITIVITY_HIGH if an outcome changes, the event count changes, or availability moves by more than one percentage point.", "",
          "| Site | Case | Flagged? | Sun: availability change / outcome / event shift | Earth: availability change / outcome / event shift |", "| --- | --- | --- | --- | --- |"]
    for b in bundles:
        for c in b["convergence"]["cases"]:
            def cell(t):
                x = c["targets"][t]
                oc = f"{x['outcome_base']} to {x['outcome_variant']}" if x["outcome_changed"] else f"{x['outcome_base']}, unchanged"
                return f"{100 * x['delta_lower']:+.2f} pp / {oc} / {x['max_event_shift_s']:.0f} s"
            L.append(f"| `{b['request']['site']['site_id']}` | `{c['case']}` | {'**yes**' if c['sensitivity_high'] else 'no'} | {cell('sun_center')} | {cell('earth_center')} |")
    na = bundles[0]["convergence"].get("not_applicable", [])
    if na:
        L += ["", "Not applicable: " + "; ".join(f"`{x['case']}` ({x['reason']})" for x in na) + "."]
    L += ["", "## Other sensitivity", "",
          "- **DEM release and azimuth step halved** (run with the base): " + ", ".join(
              f"`{b['request']['site']['site_id']}`: " + ("flagged" if any(v['sensitivity_high'] for v in b.get('sensitivity', [])) else "within tolerance") for b in bundles) + ".",
          "- **Disc size** (Sun and Earth as discs, not points): " + (
              "an outcome changes at at least one site, see the Evidence page." if any(b["disk_edge"]["matters"] for b in bundles)
              else "no outcome changes at any site; see [the RUN-001 study](RUN-001-disk-edge.md) for the availability spread."), "",
          "## Validation cards", "", "| Card | Status | Checks |", "| --- | --- | --- |"]
    for g in cards["groups"]:
        n = g["counts"]
        L.append(f"| {g['title']} | **{g['status'].replace('_', ' ')}** | {n['met']} met, {n['not_met']} not met, {n['not_evaluated']} not evaluated |")
    L += ["", "The terrain-horizon card cannot read `met` until a **second, independent skyline implementation** exists to compare against: its `independent_terrain_check` is "
          "`not evaluated` by design, and one is not built. Convergence and the DEM-release check support the numerical side only; they do not check the DEM itself.", "",
          "## Limits that apply to every number here", "",
          "- Screening and education only: not a landing-safety, power, link-budget or mission-feasibility result.",
          "- Centre-of-disc visibility, no refraction (no atmosphere), a finite 150 km horizon radius.",
          "- The run's warnings: " + ", ".join(f"`{w}`" for w in sorted({w for b in bundles for w in b['warnings']})) + ". The `EOP_PREDICTED` and leap-second warnings are expected for a 2027 window.",
          "- Only a handful of events exist (" + str(sum(len(b['targets'][t][h]['events']) for b in bundles for t in ('sun_center', 'earth_center') for h in ('terrain', 'flat')))
          + " in total across sites, targets and both horizons): the Sun never rises above the skyline at any site, so the event search is exercised mostly by Earth.",
          "- The sites are an equal-spacing rule, so this run says nothing about any real candidate site."]
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
